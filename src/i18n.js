const STORAGE_KEY = 'skystudio360.lang';
let lang = detectLang();

function detectLang() {
  try {
    const fromUrl = new URLSearchParams(window.location.search).get('lang');
    if (fromUrl && STRINGS[fromUrl]) return fromUrl;
  } catch (e) { /* ignore */ }
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch (e) { /* storage may be blocked */ }
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('ru') ? 'ru' : 'en';
}

export function getLang() { return lang; }

export function setLang(next) {
  if (!STRINGS[next]) return;
  lang = next;
  try { window.localStorage.setItem(STORAGE_KEY, next); } catch (e) { /* ignore */ }
  document.documentElement.lang = next;
}

/** Translate a key with optional {param} interpolation. Falls back to Russian, then to the key. */
export function t(key, params) {
  let s = STRINGS[lang][key] ?? STRINGS.ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(String(v));
  }
  return s;
}

/** Pick the current-language value from a { ru, en } object (or return a plain string unchanged). */
export function L(value) {
  if (value && typeof value === 'object') return value[lang] ?? value.ru ?? '';
  return value ?? '';
}

/** Apply translations to every element carrying data-i18n / data-i18n-title. */
export function applyDomTranslations(root = document, params = {}) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n, params);
  });
  root.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle, params);
  });
  document.title = t('doc.title');
  document.documentElement.lang = lang;
}
